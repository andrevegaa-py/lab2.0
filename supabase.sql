drop table if exists public.pedidos;
create table public.pedidos (
  id bigint generated always as identity primary key,   -- se genera solo: adiós "null id"
  cliente text not null,
  producto text not null,
  precio_total numeric(10,2) not null check (precio_total >= 0),
  adelanto numeric(10,2) not null default 0,
  fecha_pedido timestamptz not null default now(),
  fecha_pedido_proveedor date,
  plazo_estimado_dias int not null default 21,
  estado text not null default 'En proceso',
  pagado boolean not null default false
);

